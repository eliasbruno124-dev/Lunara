import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { PreferredLanguage } from '@prisma/client';
import {
  IsBoolean,
  IsEnum,
  IsOptional,
  IsString,
  Length,
  Matches,
  MaxLength,
  MinLength,
} from 'class-validator';
import {
  ACCOUNT_PASSWORD_MAX_LENGTH,
  ACCOUNT_PASSWORD_MIN_LENGTH,
  EXISTING_PASSWORD_MIN_LENGTH,
  IsPasswordCodePointLength,
} from './password-policy.js';

export class CredentialsDto {
  @ApiProperty({ example: 'partner-a' })
  @IsString()
  @Length(3, 64)
  @Matches(/^[\p{L}\p{N}][\p{L}\p{N}._-]*$/u)
  username!: string;

  @ApiProperty({
    minLength: ACCOUNT_PASSWORD_MIN_LENGTH,
    maxLength: ACCOUNT_PASSWORD_MAX_LENGTH,
    writeOnly: true,
    description: 'No composition rules; passphrases and password-manager values are accepted',
  })
  @IsString()
  @IsPasswordCodePointLength(ACCOUNT_PASSWORD_MIN_LENGTH, ACCOUNT_PASSWORD_MAX_LENGTH)
  password!: string;

  @ApiProperty({ example: 'Pixel 10' })
  @IsString()
  @Length(1, 120)
  @Matches(/\S/u)
  deviceName!: string;
}

export class RegisterDto extends CredentialsDto {
  @ApiProperty({ example: 'Partner A' })
  @IsString()
  @Length(1, 120)
  @Matches(/\S/u)
  displayName!: string;

  @ApiPropertyOptional({
    enum: PreferredLanguage,
    default: PreferredLanguage.DE,
  })
  @IsOptional()
  @IsEnum(PreferredLanguage)
  preferredLanguage?: PreferredLanguage;
}

export class SetupDto extends RegisterDto {
  @ApiPropertyOptional({
    deprecated: true,
    description:
      'Accepted for compatibility and ignored; the internal relationship name is generated by the server',
    minLength: 1,
    maxLength: 120,
  })
  @IsOptional()
  @IsString()
  @Length(1, 120)
  householdName?: string;

  @ApiProperty({ writeOnly: true })
  @IsString()
  @MinLength(20)
  @MaxLength(256)
  bootstrapToken!: string;
}

export class LoginDto {
  @ApiProperty({ example: 'partner-a' })
  @IsString()
  @Length(3, 64)
  @Matches(/^[\p{L}\p{N}][\p{L}\p{N}._-]*$/u)
  username!: string;

  @ApiProperty({
    minLength: EXISTING_PASSWORD_MIN_LENGTH,
    maxLength: ACCOUNT_PASSWORD_MAX_LENGTH,
    writeOnly: true,
    description: 'Existing credentials remain accepted after password-policy changes',
  })
  @IsString()
  @IsPasswordCodePointLength(EXISTING_PASSWORD_MIN_LENGTH, ACCOUNT_PASSWORD_MAX_LENGTH)
  password!: string;

  @ApiProperty({ example: 'Pixel 10' })
  @IsString()
  @Length(1, 120)
  @Matches(/\S/u)
  deviceName!: string;
}

export class RefreshDto {
  @ApiProperty({ writeOnly: true })
  @IsString()
  @MinLength(32)
  @MaxLength(256)
  refreshToken!: string;

  @ApiPropertyOptional({
    writeOnly: true,
    description:
      'Required only when rotating an OIDC-authenticated Lunara session; must be a fresh token for the originally linked identity',
  })
  @IsOptional()
  @IsString()
  @Length(64, 16_384)
  @Matches(/^\S+$/u)
  oidcAccessToken?: string;
}

export class LogoutDto {
  @ApiPropertyOptional({ writeOnly: true })
  @IsOptional()
  @IsString()
  @MinLength(32)
  @MaxLength(256)
  refreshToken?: string;
}

export class ChangePasswordDto {
  @ApiProperty({
    minLength: EXISTING_PASSWORD_MIN_LENGTH,
    maxLength: ACCOUNT_PASSWORD_MAX_LENGTH,
    writeOnly: true,
  })
  @IsString()
  @IsPasswordCodePointLength(EXISTING_PASSWORD_MIN_LENGTH, ACCOUNT_PASSWORD_MAX_LENGTH)
  currentPassword!: string;

  @ApiProperty({
    minLength: ACCOUNT_PASSWORD_MIN_LENGTH,
    maxLength: ACCOUNT_PASSWORD_MAX_LENGTH,
    writeOnly: true,
    description: 'No composition rules; passphrases and password-manager values are accepted',
  })
  @IsString()
  @IsPasswordCodePointLength(ACCOUNT_PASSWORD_MIN_LENGTH, ACCOUNT_PASSWORD_MAX_LENGTH)
  newPassword!: string;
}

export class OidcLoginDto {
  @ApiProperty({
    writeOnly: true,
    description: 'Short-lived OIDC access token issued for the Lunara audience',
  })
  @IsString()
  @Length(64, 16_384)
  @Matches(/^\S+$/u)
  accessToken!: string;

  @ApiProperty({ example: 'Pixel 10' })
  @IsString()
  @Length(1, 120)
  @Matches(/\S/u)
  deviceName!: string;

  @ApiPropertyOptional({
    minLength: 8,
    maxLength: 12,
    description:
      'When present on first sign-in, atomically joins the relationship represented by this one-time invitation',
  })
  @IsOptional()
  @IsString()
  @Length(8, 12)
  @Matches(/^[A-HJ-NP-Z2-9]+$/i)
  invitationCode?: string;

  @ApiPropertyOptional({
    enum: PreferredLanguage,
    default: PreferredLanguage.DE,
    description:
      'Used only when this exact external identity is provisioned for the first time',
  })
  @IsOptional()
  @IsEnum(PreferredLanguage)
  preferredLanguage?: PreferredLanguage;

  @ApiPropertyOptional({
    default: false,
    description:
      'Explicitly permits first sign-in to create a new isolated TRACKER relationship; omitted or false preserves login-only behavior',
  })
  @IsOptional()
  @IsBoolean()
  createIfMissing?: boolean;
}

export class OidcLinkDto {
  @ApiProperty({
    writeOnly: true,
    description: 'Short-lived OIDC access token issued for the Lunara audience',
  })
  @IsString()
  @Length(64, 16_384)
  @Matches(/^\S+$/u)
  accessToken!: string;

  @ApiProperty({
    minLength: EXISTING_PASSWORD_MIN_LENGTH,
    maxLength: ACCOUNT_PASSWORD_MAX_LENGTH,
    writeOnly: true,
    description: 'Re-authenticates the existing Lunara account before linking',
  })
  @IsString()
  @IsPasswordCodePointLength(EXISTING_PASSWORD_MIN_LENGTH, ACCOUNT_PASSWORD_MAX_LENGTH)
  currentPassword!: string;
}
